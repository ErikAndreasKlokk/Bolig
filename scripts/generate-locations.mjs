// Regenerates src/lib/locations.ts from hjem.no's area list (the one its own search box uses).
// Run with `node scripts/generate-locations.mjs` when hjem.no adds areas.
import { writeFileSync } from 'node:fs';

const res = await fetch('https://apigw.hjem.no/search-backend/api/v2/address', {
	headers: { 'User-Agent': 'bolig/1.0 (personal home-search tool)', Origin: 'https://hjem.no' }
});
if (!res.ok) throw new Error(`hjem.no area list failed: ${res.status}`);
const { data } = await res.json();

const tidy = (s) => s.replace(/\s+/g, ' ').trim();
const seg = (s) => {
	if (s.includes('/')) throw new Error(`Area value contains "/": ${s}`);
	return s;
};

const counties = data.map((c) => {
	const munis = c.suburb_collection;
	let children;
	if (munis.length === 1 && munis[0].area.length > 0) {
		// Oslo: one municipality, the same as the county, so list its districts instead
		const m = munis[0];
		children = m.area.map((a, i) => ({
			code: `${seg(c.state)}/${seg(m.suburb)}/${seg(a)}`,
			name: tidy(m.area_display[i])
		}));
	} else {
		children = munis.flatMap((m) => [
			{ code: `${seg(c.state)}/${seg(m.suburb)}`, name: tidy(m.suburb_display) },
			...m.area.map((a, i) => ({
				code: `${seg(c.state)}/${seg(m.suburb)}/${seg(a)}`,
				name: `${tidy(m.suburb_display)} – ${tidy(m.area_display[i])}`
			}))
		]);
	}
	return { code: seg(c.state), name: tidy(c.state_display), children };
});

const out = `// hjem.no areas for the search's \`address\` filter: county \`<state>\`, municipality
// \`<state>/<suburb>\`, district \`<state>/<suburb>/<area>\` (hjem.no's own lowercase values, sent as
// \`[state, suburb, area]\`). Generated by scripts/generate-locations.mjs — rerun when hjem.no adds areas.

export interface Place {
	code: string;
	name: string;
}

export interface County extends Place {
	children: Place[];
}

export const COUNTIES: County[] = ${JSON.stringify(counties, null, '\t')};
`;
writeFileSync(new URL('../src/lib/locations.ts', import.meta.url), out);
console.log(
	`Wrote ${counties.length} counties, ${counties.reduce((n, c) => n + c.children.length, 0)} areas`
);
